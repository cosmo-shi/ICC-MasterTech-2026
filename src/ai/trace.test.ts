// A worked sequence on a seeded test profile: captured try → evidence → Bayesian inference →
// teaching action → fresh related task, compared with the rules baseline at every step.
// `npm run decisions` rewrites docs/MODEL_DECISIONS.md from this test (never hand-edit it).
// A seeded profile illustrates states; it does not show that anyone learns more.

import { describe, expect, it } from 'vitest';
import { lessonById } from '../data/catalog.ts';
import { soundingEvents } from '../music/events.ts';
import { freshRelated } from '../music/versions.ts';
import type { AttemptRecord } from '../store/db.ts';
import { LESSON_INFOS, skillById } from './learner.ts';
import { routeFrom } from '../data/curriculum.ts';
import { type TraceStep, traceLearner } from './trace.ts';

let t = 0;
const mk = (activityId: string, kind: AttemptRecord['kind'], rv: number, extra: Partial<AttemptRecord> = {}): AttemptRecord => ({
  id: `seed-${++t}`,
  createdAt: Date.UTC(2026, 10, 9, 9, t),
  activityId,
  activityVersion: '1',
  kind,
  instrument: 'drums',
  tempoBpm: 80,
  support: { hintLevel: 0, heardExample: false, largeControls: false, simplified: false, aiEnabled: true, slower: false },
  inputs: [],
  summary: kind === 'check' ? undefined : { expected: 2, correctSound: 2, wrong: 0, missed: 0, extra: rv, restViolations: rv, early: 0, onTime: 2, late: 0, durationOk: 0, durationIssues: 0 },
  passed: kind === 'check' ? false : rv === 0,
  ...extra,
});

// L01's summary uses four beats.
const pulse = (kind: AttemptRecord['kind'], onTime: number): AttemptRecord => {
  const a = mk('L01', kind, 0);
  return { ...a, summary: { ...a.summary!, expected: 4, correctSound: 4, onTime, late: 4 - onTime }, passed: onTime === 4 };
};

const SEQUENCE: { a: AttemptRecord; note: string }[] = [
  { a: pulse('practice', 4), note: 'Find the pulse, practice: all four on the beat.' },
  { a: pulse('independent', 4), note: 'Find the pulse, a new pattern on their own: all on the beat.' },
  { a: mk('L02', 'practice', 1), note: 'Leave a space: a tap in the rest.' },
  { a: mk('L02', 'practice', 2), note: 'Leave a space again: two taps in the rests.' },
  {
    a: mk('L02', 'check', 0, { probe: { skill: 'rests', check: 'listen', right: true, offeredBy: 'learner-model', support: 'count-aloud', supportTaken: true } }),
    note: 'Learner chose the Listen check: heard their own take beside a verified version with the rest taps taken out, and picked the quiet one. Took the suggested support: counting under the music.',
  },
  { a: mk('L02', 'practice', 0, { support: { hintLevel: 0, heardExample: true, largeControls: false, simplified: false, aiEnabled: true, slower: false } }), note: 'A fresh related pattern (the rests moved), with counting shown: rests quiet.' },
  { a: mk('L02', 'independent', 0), note: 'On their own, a new pattern, no hints: rests quiet.' },
];

const pct = (p: number) => p.toFixed(2);
const title = (id?: string) => (id ? (lessonById(id)?.title ?? id) : '—');

function markdown(steps: TraceStep[], off: TraceStep[]): string {
  const fresh = freshRelated(lessonById('L02')!.practice!, 1);
  const rows = steps.map((s, i) => {
    const ev = s.changes.length ? s.changes.map((c) => `${skillById(c.skill).name}: ${c.pass ? 'pass' : 'miss'}`).join('; ') : '—';
    const inf = s.changes.length
      ? s.changes.map((c) => `${skillById(c.skill).name} ${pct(c.before)} → ${pct(c.after)} (${c.bandAfter}${c.uncertain ? ', too few tries' : ''})`).join('; ')
      : 'unchanged';
    const act = (x: TraceStep['model']) => [x.checkIn ? `offer checks (${x.checkIn.fails} misses)` : '', x.start.length ? `start: ${x.start.join(', ')}` : '', `next: ${title(x.next)}`].filter(Boolean).join('; ');
    return `| ${i + 1} | ${SEQUENCE[i].note} | ${s.why} | ${ev} | ${inf} | ${act(s.model)}${s.model.why ? ` — “${s.model.why}”` : ''} | ${act(s.rules)} | ${s.differs ? 'yes' : 'no'} |`;
  });
  return `# Model decisions on a seeded test profile

Generated by \`npm run decisions\` from \`src/ai/trace.test.ts\`. Do not hand-edit.

This walks one **seeded test profile** (made-up tries, not a child) through Carmen's learner model, Bayesian Knowledge Tracing (\`src/ai/bkt.ts\`), and shows each layer separately:

1. **The try**: what was recorded (activity, help used, checker facts).
2. **Evidence**: checker facts turned into pass or miss per skill, and how much the try counts (practice and help count for less; checks count for nothing).
3. **Inference**: the probability the skill is known, before and after, with its band. "Too few tries" means the model will not act on it yet.
4. **Teaching action**: what the model chose, next to the reviewed rules baseline (the pathway route, plus checks after three misses in a row in one visit).

It illustrates how evidence and uncertainty change the action. It does **not** show that the model helps anyone learn, or that it beats the rules for real children: that needs a supervised trial with educators. Notation, sound mapping and playback verification are checked by their own tests and are not part of the learner model.

| Step | Try | How much it counts | Evidence | Inference (p known) | Model action | Rules baseline | Different? |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

**Fresh related task used at step 6:** Leave a space with the pattern rotated by a beat: written sounds at ticks ${soundingEvents(fresh).map((e) => e.onset).join(', ')} (the lesson's practice pattern has ${soundingEvents(lessonById('L02')!.practice!).map((e) => e.onset).join(', ')}).

**With the model switched off** the same tries give: ${off.map((s, i) => `${i + 1}. ${s.model.checkIn ? 'offer checks; ' : ''}next ${title(s.model.next)}`).join(' · ')}.

What to notice:
- Step 3: one miss lowers the rests estimate but leaves it "too few tries", so the model does not offer checks or extra support yet. One response is never treated as a diagnosis.
- Step 4: a second miss gives enough evidence that rests still need practice. The model offers the three checks and suggests hearing it first; the rules baseline would not offer checks until a third miss in a row.
- Step 5: the check result is stored for the teacher but does not move the estimate.
- Step 6: success with help (practice, heard first) raises the estimate by less than success on their own would.
- Step 7: only a pass on their own can make the skill "secure".
`;
}

describe('worked model sequence (seeded test profile)', () => {
  const ctx = { route: routeFrom('1-2'), aiEnabled: true };
  const steps = traceLearner(SEQUENCE.map((s) => s.a), LESSON_INFOS, ctx);
  const off = traceLearner(SEQUENCE.map((s) => s.a), LESSON_INFOS, { ...ctx, aiEnabled: false });

  it('one miss is too little evidence to act on', () => {
    expect(steps[2].changes.find((c) => c.skill === 'rests')!.uncertain).toBe(true);
    expect(steps[2].model.checkIn).toBeNull();
  });
  it('repeated misses change the teaching action, and the rules baseline does not yet', () => {
    expect(steps[3].model.checkIn?.skill).toBe('rests');
    expect(steps[3].rules.checkIn).toBeNull();
    expect(steps[3].differs).toBe(true);
  });
  it('a check is not evidence', () => {
    expect(steps[4].changes).toEqual([]);
    expect(steps[4].weight).toBe(0);
  });
  it('assisted success moves the estimate less than independent success', () => {
    const r = (i: number) => steps[i].changes.find((c) => c.skill === 'rests')!;
    expect(r(6).after - r(6).before).toBeGreaterThan(r(5).after - r(5).before);
    expect(r(5).bandAfter).not.toBe('secure');
    // After a pass, checks are no longer offered and the reason no longer says "your last tries".
    expect(steps[5].model.checkIn).toBeNull();
    expect(steps[6].model.why).not.toMatch(/last \d+ tries/);
  });
  it('with the model off, the app falls back to the rules', () => {
    expect(off.every((s) => s.model.why === 'Model off: rules')).toBe(true);
  });
  it('writes the decision record when asked', () => {
    const md = markdown(steps, off);
    expect(md).toContain('| 4 |');
    if (import.meta.env.VITE_WRITE_DECISIONS) console.log('MODEL_DECISIONS_MD:' + JSON.stringify(md));
  });
});
